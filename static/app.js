  const Sound = (() => {
    let ctx = null;
    function audio() {
      const C = window.AudioContext || window.webkitAudioContext;
      if (!C) return null;
      if (!ctx) ctx = new C();
      return ctx;
    }
    function unlock() {
      const c = audio();
      if (c && c.state === "suspended") c.resume().catch(() => {});
    }
    function tock(kind) {
      const c = audio();
      if (!c || c.state !== "running") return;
      const t0 = c.currentTime;
      const go = kind === "go";
      const soft = kind === "soft";
      const jitter = (Math.random() - 0.5) * 70;
      const clickHz = (go ? 1520 : soft ? 2280 : 1880) + jitter;
      const noiseMs = go ? 0.016 : 0.012;
      const n = Math.max(32, Math.floor(noiseMs * c.sampleRate));
      const buf = c.createBuffer(1, n, c.sampleRate);
      const data = buf.getChannelData(0);
      for (let i = 0; i < n; i += 1) {
        const env = 1 - i / n;
        data[i] = (Math.random() * 2 - 1) * env * env;
      }
      const noise = c.createBufferSource();
      noise.buffer = buf;
      const hp = c.createBiquadFilter();
      hp.type = "highpass";
      hp.frequency.setValueAtTime(go ? 700 : 1200, t0);
      const bp = c.createBiquadFilter();
      bp.type = "bandpass";
      bp.frequency.setValueAtTime(clickHz, t0);
      bp.Q.setValueAtTime(go ? 0.7 : 1.1, t0);
      const ng = c.createGain();
      ng.gain.setValueAtTime(go ? 0.42 : soft ? 0.26 : 0.34, t0);
      ng.gain.exponentialRampToValueAtTime(0.0001, t0 + (go ? 0.05 : 0.036));
      noise.connect(hp);
      hp.connect(bp);
      bp.connect(ng);
      ng.connect(c.destination);
      noise.start(t0);
      const osc = c.createOscillator();
      const og = c.createGain();
      osc.type = "triangle";
      osc.frequency.setValueAtTime(clickHz, t0);
      osc.frequency.exponentialRampToValueAtTime(clickHz * 0.68, t0 + 0.028);
      og.gain.setValueAtTime(go ? 0.2 : soft ? 0.11 : 0.15, t0);
      og.gain.exponentialRampToValueAtTime(0.0001, t0 + (go ? 0.055 : 0.04));
      osc.connect(og);
      og.connect(c.destination);
      osc.start(t0);
      osc.stop(t0 + 0.07);
    }
    function play(kind) {
      if (!state.sound) return;
      const c = audio();
      if (!c) return;
      if (c.state === "suspended") {
        c.resume().then(() => play(kind)).catch(() => {});
        return;
      }
      tock(kind);
    }
    return { unlock, play };
  })();

  function extractIgUrl(text) {
    const src = String(text || "");
    const li = src.match(/https?:\/\/(?:www\.)?l\.instagram\.com\/[^\s<>"']+/i);
    if (li) {
      try {
        const dest = new URL(li[0]).searchParams.get("u");
        if (dest) return extractIgUrl(dest);
      } catch (_) {}
    }
    const m = src.match(/https?:\/\/(?:www\.|m\.|l\.)?(?:instagram\.com|instagr\.am)\/[^\s<>"']+/i);
    if (!m) return "";
    const raw = m[0].replace(/[),.\]>]+$/, "");
    try {
      const parsed = new URL(raw);
      const path = parsed.pathname.replace(/\/{2,}/g, "/").replace(/\/+$/, "");
      if (!path || path === "/") return "";
      return `https://www.instagram.com${path}/`;
    } catch {
      return raw.split(/[?#]/)[0];
    }
  }

  function prettyIgUrl(url) {
    try {
      const parsed = new URL(url);
      return `${parsed.host.replace(/^www\./, "")}${parsed.pathname}`.replace(/\/+$/, "");
    } catch {
      return String(url || "").replace(/^https?:\/\/(www\.)?/, "").split(/[?#]/)[0];
    }
  }

