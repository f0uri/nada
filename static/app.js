  function compact(n) {
    if (n == null || n === "") return "—";
    const x = Number(n);
    if (!Number.isFinite(x)) return "—";
    if (x >= 1e6) return `${(x / 1e6).toFixed(x >= 1e7 ? 0 : 1).replace(/\.0$/, "")}M`;
    if (x >= 1e3) return `${(x / 1e3).toFixed(x >= 1e4 ? 0 : 1).replace(/\.0$/, "")}K`;
    return x.toLocaleString(state.lang === "ar" ? "ar" : "en");
  }

